/**
 * gen-abi.ts - write the ABIs the v2 scripts and the dashboard use.
 *
 *   npm run abi:v2      (runs forge build first)
 *
 * Writes scripts/v2/abi.ts from the Foundry artifacts, so the CLI and the
 * dashboard do not depend on out/ at run time. Re-run after any contract change;
 * `test/v2/Vectors.t.sol` and the typecheck catch a stale file.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

function abiOf(file: string, name: string): unknown {
  return JSON.parse(readFileSync(join(root, "out", file, `${name}.json`), "utf8")).abi;
}

const vault = abiOf("PealTenderV2.sol", "PealTenderV2");
const book = abiOf("TenderBook.sol", "TenderBook");
const erc20 = [
  { type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ name: "a", type: "address" }], outputs: [{ type: "uint256" }] },
  { type: "function", name: "decimals", stateMutability: "view", inputs: [], outputs: [{ type: "uint8" }] },
  { type: "function", name: "symbol", stateMutability: "view", inputs: [], outputs: [{ type: "string" }] },
  {
    type: "function",
    name: "approve",
    stateMutability: "nonpayable",
    inputs: [{ name: "spender", type: "address" }, { name: "amount", type: "uint256" }],
    outputs: [{ type: "bool" }],
  },
];
const keyStatus = [
  {
    type: "function",
    name: "pqcKeyStatus",
    stateMutability: "view",
    inputs: [{ name: "account", type: "address" }],
    outputs: [
      { name: "registered", type: "bool" },
      { name: "algorithmId", type: "uint8" },
      { name: "publicKey", type: "bytes" },
      { name: "possessionProven", type: "bool" },
    ],
  },
];

const out = [
  "// Generated by scripts/v2/gen-abi.ts from the Foundry artifacts. Do not edit.",
  `export const vaultAbi = ${JSON.stringify(vault)} as const;`,
  `export const tenderBookAbi = ${JSON.stringify(book)} as const;`,
  `export const erc20Abi = ${JSON.stringify(erc20)} as const;`,
  `/** The live precompile returns four values; the SDK's ABI lists three (see the kit's docs/spikes.md, S6). */`,
  `export const pqcKeyStatusAbi = ${JSON.stringify(keyStatus)} as const;`,
  "",
].join("\n");
writeFileSync(join(root, "scripts", "v2", "abi.ts"), out);
console.log("wrote scripts/v2/abi.ts");
