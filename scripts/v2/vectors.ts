/**
 * vectors.ts - write vectors/v2-actions.json from the TypeScript encoders.
 *
 *   npm run vectors:v2
 *
 * `test/v2/Vectors.t.sol` reads the file and checks every hash and message
 * against Solidity's own `abi.encode`, so the CLI and the contract cannot drift
 * apart silently.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Address, Hex } from "viem";
import { quorumMessage, anyMessage } from "pqkit/pqauthset";
import { actionIdOf, argsHash, metadataHash, opData, type OpenParams, type SaleConfig } from "./encode.ts";
import { ROOT } from "./vault.ts";

const A = (n: number) => `0x${n.toString(16).padStart(40, "0")}` as Address;
const vault = A(0x7e11);
const factory = A(0xfac);
const fusd = A(0xf05d);
const peal = A(0x9ea1);
const member = A(0xa11ce);

const open: OpenParams = {
  budget: 100_000_000n,
  floorPrice: 1_000_000n,
  tickSize: 100_000n,
  numTicks: 10,
  endTime: 1_800_086_400n,
  maxOffers: 50,
  minQuantity: 10n ** 16n,
};
const sale: SaleConfig = {
  issuer: vault,
  saleToken: fusd,
  quoteToken: peal,
  totalSupply: 400_000_000n,
  saleDecimals: 6,
  reservePrice: 5n * 10n ** 18n,
  tickSize: 10n ** 17n,
  numTicks: 20,
  startTime: 1_800_000_000n,
  endTime: 1_800_086_400n,
  releaseDeadline: 1_800_172_800n,
  minBidQuantity: 1_000_000n,
  maxQuantityPerAddress: 0n,
  maxBids: 64,
  bidBond: 10n ** 18n,
  protocolFeeBps: 0,
  feeRecipient: A(0),
  committeeSetId: `0x${"c0".repeat(32)}` as Hex,
  metadataHash: metadataHash("Buyback 1", "vault sells fUSD for PEAL-T"),
};
const members = [A(0xa), A(0xb), A(0xc)];

const fields = { chainId: 9800n, verifier: vault, nonce: 7n, deadline: 1_800_003_600n };
const sweepHash = argsHash.sweep(fusd, member, 1_000_000n);

const out = {
  note: "Generated by scripts/v2/vectors.ts; checked by test/v2/Vectors.t.sol.",
  addresses: { vault, factory, fusd, peal, member },
  actions: {
    deposit: actionIdOf("deposit"),
    openTender: actionIdOf("openTender"),
    cancelTender: actionIdOf("cancelTender"),
    sweep: actionIdOf("sweep"),
    queue: actionIdOf("queue"),
    veto: actionIdOf("veto"),
    startSealedSale: actionIdOf("startSealedSale"),
    cancelSealedSale: actionIdOf("cancelSealedSale"),
  },
  argsHashes: {
    deposit: argsHash.deposit(member, 50_000_000n),
    sweep: sweepHash,
    openTender: argsHash.openTender(open),
    cancelTender: argsHash.cancelTender(3n),
    queueSweep: argsHash.queue("Sweep", opData.Sweep(fusd, member, 3_000_000_000n)),
    queueSigners: argsHash.queue("SetSigners", opData.SetSigners(members, 2n)),
    queueDelay: argsHash.queue("SetDelay", opData.SetDelay(7200n)),
    queueCap: argsHash.queue("SetDailyCap", opData.SetDailyCap(fusd, 10_000_000n)),
    queueFactory: argsHash.queue("SetAuctionFactory", opData.SetAuctionFactory(factory)),
    veto: argsHash.veto(5n),
    startSealedSale: argsHash.startSealedSale(factory, sale, "Buyback 1", "vault sells fUSD for PEAL-T"),
    cancelSealedSale: argsHash.cancelSealedSale(A(0xa0c7)),
  },
  metadataHash: sale.metadataHash,
  quorumSweepMessage: quorumMessage({ ...fields, action: actionIdOf("sweep"), argsHash: sweepHash }, member),
  vetoMessage: anyMessage({ ...fields, action: actionIdOf("veto"), argsHash: argsHash.veto(5n) }, member),
};

mkdirSync(join(ROOT, "vectors"), { recursive: true });
writeFileSync(join(ROOT, "vectors", "v2-actions.json"), JSON.stringify(out, null, 2) + "\n");
console.log("wrote vectors/v2-actions.json");
